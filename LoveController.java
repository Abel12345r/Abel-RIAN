package com.lovestory;

import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpSession;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.http.HttpStatus;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.web.bind.annotation.*;
import org.springframework.web.server.ResponseStatusException;
import java.security.MessageDigest;
import java.util.*;
import java.util.concurrent.ConcurrentHashMap;

@RestController
@RequestMapping("/api")
public class LoveController {
    private final JdbcTemplate db;
    private final Map<String, Integer> failedLogins = new ConcurrentHashMap<>();
    @Value("${LOVE_PASSKEY}") private String passkey;

    public LoveController(JdbcTemplate db) {
        this.db = db;
        db.execute("CREATE TABLE IF NOT EXISTS notes (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, sender VARCHAR(40) NOT NULL, recipient VARCHAR(40) NOT NULL, message VARCHAR(1200) NOT NULL, created TIMESTAMP DEFAULT CURRENT_TIMESTAMP)");
        db.execute("CREATE TABLE IF NOT EXISTS surprises (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, sender VARCHAR(40) NOT NULL, recipient VARCHAR(40) NOT NULL, title VARCHAR(100) NOT NULL, body VARCHAR(4000) NOT NULL, created TIMESTAMP DEFAULT CURRENT_TIMESTAMP)");
        db.execute("CREATE TABLE IF NOT EXISTS heartbeats (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, sender VARCHAR(40) NOT NULL, recipient VARCHAR(40) NOT NULL, created TIMESTAMP DEFAULT CURRENT_TIMESTAMP)");
    }

    @PostMapping("/auth/login")
    public Map<String, Object> login(@RequestBody Login body, HttpServletRequest request) {
        String ip = Optional.ofNullable(request.getRemoteAddr()).orElse("unknown");
        if (failedLogins.getOrDefault(ip, 0) >= 10) throw new ResponseStatusException(HttpStatus.TOO_MANY_REQUESTS, "Too many attempts. Try again later.");
        String username = clean(body.username, 40, "username");
        if (!(username.equalsIgnoreCase("Abel") || username.equalsIgnoreCase("Rian")) || body.password == null || passkey.isBlank() || !MessageDigest.isEqual(passkey.getBytes(), body.password.getBytes())) {
            failedLogins.merge(ip, 1, Integer::sum); throw new ResponseStatusException(HttpStatus.UNAUTHORIZED, "Name or passkey is incorrect.");
        }
        failedLogins.remove(ip);
        HttpSession session = request.getSession(true); request.changeSessionId();
        session.setAttribute("partner", username.substring(0,1).toUpperCase()+username.substring(1).toLowerCase());
        session.setAttribute("csrf", UUID.randomUUID().toString());
        return Map.of("name", session.getAttribute("partner"), "csrf", session.getAttribute("csrf"));
    }
    @GetMapping("/auth/me") public Map<String,Object> me(HttpSession session) { String p=partner(session); return Map.of("name",p,"csrf",session.getAttribute("csrf")); }
    @PostMapping("/auth/logout") public void logout(HttpSession session) { session.invalidate(); }

    @GetMapping("/notes") public List<Map<String,Object>> notes(HttpSession session) {
        String who=partner(session);
        return db.queryForList("SELECT id,sender,recipient,message,created FROM notes WHERE sender=? OR recipient=? ORDER BY created DESC",who,who);
    }
    @PostMapping("/notes") public Map<String,Object> addNote(@RequestBody Note body,HttpSession session) {
        String who=partner(session), recipient=other(body.recipient,who), msg=clean(body.message,1200,"message");
        db.update("INSERT INTO notes(sender,recipient,message) VALUES(?,?,?)",who,recipient,msg);
        return Map.of("sender",who,"recipient",recipient,"message",msg);
    }
    @PutMapping("/notes/{id}") public void editNote(@PathVariable long id,@RequestBody Note body,HttpSession session) {
        String who=partner(session), msg=clean(body.message,1200,"message");
        if(db.update("UPDATE notes SET message=? WHERE id=? AND sender=?",msg,id,who)==0) throw new ResponseStatusException(HttpStatus.NOT_FOUND,"Note not found or not yours to edit.");
    }
    @GetMapping("/surprises") public List<Map<String,Object>> surprises(HttpSession session) {
        String who=partner(session);
        return db.queryForList("SELECT id,sender,recipient,title,body,created FROM surprises WHERE sender=? OR recipient=? ORDER BY created DESC",who,who);
    }
    @PostMapping("/surprises") public Map<String,Object> addSurprise(@RequestBody Surprise body,HttpSession session) {
        String who=partner(session), recipient=other(body.recipient,who), title=clean(body.title,100,"title"), content=clean(body.body,4000,"body");
        db.update("INSERT INTO surprises(sender,recipient,title,body) VALUES(?,?,?,?)",who,recipient,title,content);
        return Map.of("sender",who,"recipient",recipient,"title",title,"body",content);
    }
    @PutMapping("/surprises/{id}") public void editSurprise(@PathVariable long id,@RequestBody Surprise body,HttpSession session) {
        String who=partner(session), title=clean(body.title,100,"title"), content=clean(body.body,4000,"body");
        if(db.update("UPDATE surprises SET title=?,body=? WHERE id=? AND sender=?",title,content,id,who)==0) throw new ResponseStatusException(HttpStatus.NOT_FOUND,"Surprise not found or not yours to edit.");
    }
    @PostMapping("/heartbeats") public Map<String,Object> heartbeat(HttpSession session) {
        String who=partner(session), recipient=who.equals("Abel")?"Rian":"Abel";
        db.update("INSERT INTO heartbeats(sender,recipient) VALUES(?,?)",who,recipient);
        return Map.of("sent",true,"recipient",recipient,"message","Your heartbeat is on its way.");
    }
    @GetMapping("/heartbeats") public List<Map<String,Object>> getHeartbeats(HttpSession session) {
        String who=partner(session);
        return db.queryForList("SELECT id,sender,created FROM heartbeats WHERE recipient=? AND created > DATEADD('HOUR',-24,CURRENT_TIMESTAMP) ORDER BY created DESC",who);
    }
    private String partner(HttpSession s) { Object p=s.getAttribute("partner"); if(p==null)throw new ResponseStatusException(HttpStatus.UNAUTHORIZED,"Sign in required."); return p.toString(); }
    private String other(String value,String sender) { if(value==null) throw new ResponseStatusException(HttpStatus.BAD_REQUEST,"Recipient is required."); String r=value.trim(); if(!r.equals("Abel")&&!r.equals("Rian")||r.equals(sender))throw new ResponseStatusException(HttpStatus.BAD_REQUEST,"Choose your partner as recipient.");return r; }
    private String clean(String s,int max,String field) { if(s==null||s.trim().isEmpty()||s.trim().length()>max)throw new ResponseStatusException(HttpStatus.BAD_REQUEST,"Invalid "+field+"."); return s.trim(); }
    public static class Login { public String username,password; }
    public static class Note { public String recipient,message; }
    public static class Surprise { public String recipient,title,body; }
}
